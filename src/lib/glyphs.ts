/**
 * Single-stroke "ball and stick" manuscript glyphs used for tracing.
 *
 * Coordinate system (y grows downward):
 *   y = 0    top line (capitals, ascenders)
 *   y = 50   dashed middle line (x-height)
 *   y = 100  baseline
 *   y = 150  descender line
 *
 * Each stroke is an SVG path string, listed in the order a child should write it.
 * `dots` are pen taps (the dots on i and j).
 */
export interface Glyph {
  width: number;
  strokes: string[];
  dots?: [number, number][];
}

const G = (width: number, strokes: string[], dots?: [number, number][]): Glyph => ({
  width,
  strokes,
  dots,
});

