export const SPACE_WIDTH = 52;
export const LETTER_GAP = 16;

export function hasGlyph(ch: string): boolean {
  return ch === ' ' || ch in GLYPHS;
}

/** Width in glyph units of a string laid out with standard spacing. */
export function measureText(text: string): number {
  let w = 0;
  let first = true;
  for (const ch of text) {
    if (ch === ' ') {
      w += SPACE_WIDTH;
      first = true;
      continue;
    }
    const g = GLYPHS[ch];
    if (!g) continue;
    if (!first) w += LETTER_GAP;
    w += g.width;
    first = false;
  }
  return w;
}

/** Does the text use the descender area (g, j, p, q, y)? */
export function usesDescender(text: string): boolean {
  return /[gjpqy,]/.test(text);
}
